// Turns content/ into src/content.ts, the module the app imports, so the content works offline and ships with EAS
// Update. CI runs it and fails when the committed module differs.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const read = (path) => readFileSync(join(root, path), 'utf8').replace(/\r\n/g, '\n');

function fail(message) {
  console.error(message);
  process.exit(1);
}

const phones = JSON.parse(read('content/telefones.json'));
for (const phone of phones) {
  if (typeof phone.category !== 'string' || typeof phone.name !== 'string' || !/^\d+$/.test(phone.number)
    || typeof phone.emergency !== 'boolean') {
    fail(`telefones.json: ${JSON.stringify(phone)} precisa de category, name, number (só dígitos) e emergency.`);
  }
}

// Frontmatter is "key: value" lines; conditions is a list, [a, b].
function parseArticle(file) {
  const match = read(`content/artigos/${file}`).match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) {
    fail(`${file}: falta o frontmatter entre ---.`);
  }
  const fields = Object.fromEntries(match[1].split('\n').map((line) => {
    const [, key, value] = line.match(/^(\w+):\s*(.*)$/) ?? fail(`${file}: linha inválida no frontmatter: ${line}`);
    return [key, value.replace(/^"(.*)"$/, '$1')];
  }));
  const conditions = fields.conditions?.match(/^\[(.*)\]$/)?.[1];
  if (!fields.title || !fields.theme || conditions === undefined || !/^\d{4}-\d{2}-\d{2}$/.test(fields.date ?? '')) {
    fail(`${file}: o frontmatter precisa de title, theme, conditions ([] ou [codigo, ...]) e date (AAAA-MM-DD).`);
  }
  return {
    slug: file.replace(/\.md$/, ''),
    title: fields.title,
    theme: fields.theme,
    conditions: conditions.split(',').map((c) => c.trim()).filter(Boolean),
    date: fields.date,
    body: match[2].trim(),
  };
}

const articles = readdirSync(join(root, 'content/artigos')).filter((f) => f.endsWith('.md')).sort().map(parseArticle);

writeFileSync(join(root, 'src/content.ts'), `// Generated by \`npm run content\` from content/. Don't edit; change the files there.

export type Phone = { category: string; name: string; number: string; emergency: boolean };

export type Article = { slug: string; title: string; theme: string; conditions: string[]; date: string; body: string };

export const phones: Phone[] = ${JSON.stringify(phones, null, 2)};

export const articles: Article[] = ${JSON.stringify(articles, null, 2)};
`);
